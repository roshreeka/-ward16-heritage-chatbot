import type { Reference, Site } from '../types'

interface Props {
  references: Reference[]
  site: Site | null
  onClose: () => void
}

export function SourcesPanel({ references, site, onClose }: Props) {
  return (
    <div className="overlay" role="dialog" aria-modal="true" aria-label="Research sources" onClick={onClose}>
      <div className="panel" onClick={(e) => e.stopPropagation()}>
        <div className="panel-header">
          <h2>Research sources</h2>
          <button className="icon-btn" onClick={onClose} aria-label="Close">
            ×
          </button>
        </div>
        {site && site.photos.length > 0 && (
          <section>
            <h3>Photographs of {site.name}</h3>
            <ul>
              {site.photos.map((p) => (
                <li key={p.url ?? p.label}>
                  {p.url ? (
                    <a href={p.url} target="_blank" rel="noreferrer">
                      {p.label}
                    </a>
                  ) : (
                    p.label
                  )}{' '}
                  — {p.credit}
                </li>
              ))}
            </ul>
          </section>
        )}
        <section>
          <h3>Selected references</h3>
          <ol>
            {references.map((r) => (
              <li key={r.number} value={r.number}>
                {r.text}{' '}
                {r.url && (
                  <a href={r.url} target="_blank" rel="noreferrer">
                    Link
                  </a>
                )}
              </li>
            ))}
          </ol>
        </section>
        <p className="note">
          Source: “Heritage Landmarks of Kathmandu Metropolitan City – Ward 16”, a desk research report. Answers are
          generated by AI from this report and may contain mistakes.
        </p>
      </div>
    </div>
  )
}
